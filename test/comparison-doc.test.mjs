// @ts-check
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { FIXTURES } from "../scripts/fixtures.mjs";
import { LOSSES, PROBES } from "../scripts/compare/probes.mjs";

const root = join(import.meta.dirname, "..");
const versions = JSON.parse(readFileSync(join(root, "scripts", "compare", "versions.json"), "utf8"));
const doc = readFileSync(join(root, "docs", "COMPARISON.md"), "utf8");

test("every probe has a unique id, a feature, a competitor and a real fixture", () => {
  assert.ok(PROBES.length >= 15);
  assert.equal(new Set(PROBES.map((p) => p.id)).size, PROBES.length);
  for (const p of PROBES) {
    assert.match(p.id, /^P\d\d$/);
    assert.ok(p.feature && p.competitor, p.id);
    assert.ok(p.fixture in FIXTURES, `${p.id}: unknown fixture ${p.fixture}`);
    assert.equal(typeof p.run, "function");
  }
  assert.ok(LOSSES.length >= 3);
});

test("docs/COMPARISON.md was generated from the pinned versions and covers every probe", () => {
  assert.match(doc, /^Generated by `npm run compare` on \d{4}-\d{2}-\d{2}\./m);
  // If versions.json changes and the document is not regenerated, this fails.
  assert.ok(doc.includes(`| git-fame | ${versions["git-fame"].version} |`), "git-fame version");
  assert.ok(doc.includes(`| git-who | ${versions["git-who"].tag} `), "git-who version");
  assert.ok(doc.includes(`| git-extras | ${versions["git-extras"].tag} `), "git-extras version");
  assert.ok(doc.includes(`| git-truck | ${versions["git-truck"].version}`), "git-truck version");
  assert.ok(/^\| hercules \| /m.test(doc), "hercules row, installed or failed");
  for (const p of PROBES) assert.match(doc, new RegExp(`^\\| ${p.id} \\|`, "m"), p.id);
  assert.match(doc, /## Stated losses/);
  assert.match(doc, /No competitor code is copied into this repository/);
  assert.doesNotMatch(doc, /\| not run \|/, "a probe that did not run must be fixed or explained, not committed");
});
