// Turn probe outcomes into docs/COMPARISON.md. Pure functions, no I/O, so the tests can feed canned outcomes.

/**
 * What a probe concluded.
 *   tie        both tools ran and printed the same numbers
 *   ours-only  the competitor has no such option or fails on this input, and ours works
 *   differs    both ran and the numbers differ; the note says why
 *   ours-lacks the competitor has the feature and ours does not (a stated loss)
 *   info       a measurement that is not a win or a loss (timing, a different quantity)
 *   not-run    a tool needed for the row could not be run on this machine
 * @typedef {"tie" | "ours-only" | "differs" | "ours-lacks" | "info" | "not-run"} Verdict
 * @typedef {{ verdict: Verdict, ours: string, theirs: string, note: string }} Outcome
 * @typedef {{ id: string, feature: string, competitor: string, fixture: string }} ProbeInfo
 */

/** The verdicts a launch text may rely on. Everything else is a stated difference, loss or non-result. */
export const CLAIMABLE = new Set(["tie", "ours-only"]);

const LABEL = {
  tie: "tie",
  "ours-only": "ours only",
  differs: "differs",
  "ours-lacks": "ours lacks (stated loss)",
  info: "info",
  "not-run": "not run",
};

/** @param {string} s */
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

/**
 * @param {{
 *   date: string,
 *   machine: string,
 *   tools: { name: string, version: string, license: string, note: string }[],
 *   results: { probe: ProbeInfo, outcome: Outcome }[],
 *   losses: { feature: string, who: string, issue: string }[],
 * }} input
 * @returns {string}
 */
export function renderComparison(input) {
  const out = [];
  out.push("# Comparison with other tools");
  out.push("");
  out.push(`Generated by \`npm run compare\` on ${input.date}. Do not edit by hand: the run date and every number below come from that run.`);
  out.push("");
  out.push(`Machine: ${input.machine}. Fixtures are built by \`scripts/fixtures.mjs\` with fixed authors, dates and messages, so the same commits exist on every run.`);
  out.push("");
  out.push("## Tools and versions");
  out.push("");
  out.push("| Tool | Version | Licence | Used as |");
  out.push("| --- | --- | --- | --- |");
  for (const t of input.tools) out.push(`| ${cell(t.name)} | ${cell(t.version)} | ${cell(t.license)} | ${cell(t.note)} |`);
  out.push("");
  out.push("No competitor code is copied into this repository. git-fame is MPL-2.0 and is only started as a program to read its output.");
  out.push("");
  out.push("## Features, measured on the same repositories");
  out.push("");
  out.push("| Id | Feature | Against | Fixture | surviving-lines | Them | Verdict | Why |");
  out.push("| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const { probe, outcome } of input.results) {
    out.push(`| ${probe.id} | ${cell(probe.feature)} | ${cell(probe.competitor)} | ${probe.fixture} | ${cell(outcome.ours)} | ${cell(outcome.theirs)} | ${LABEL[outcome.verdict]} | ${cell(outcome.note)} |`);
  }
  out.push("");
  out.push("## Stated losses");
  out.push("");
  out.push("Features a competitor has and this tool does not. They stay on this page until they are built.");
  out.push("");
  for (const l of input.losses) out.push(`- ${l.feature} (${l.who}). ${l.issue}`);
  out.push("");
  out.push("## What a launch text may claim");
  out.push("");
  const claim = input.results.filter((r) => CLAIMABLE.has(r.outcome.verdict));
  out.push("Only rows where the verdict is `tie` or `ours only`:");
  out.push("");
  for (const r of claim) out.push(`- ${r.probe.id}: ${r.probe.feature} against ${r.probe.competitor} (${LABEL[r.outcome.verdict]})`);
  if (claim.length === 0) out.push("- none yet");
  out.push("");
  return out.join("\n");
}
